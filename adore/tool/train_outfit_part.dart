import 'dart:io';
import 'dart:math';

import 'package:adore/services/local_image_analysis.dart';

/// Trains hierarchical on-device classifiers from `D:\fyp project\dataset`.
///
/// Run from the adore folder:
///   flutter pub run tool/train_outfit_part.dart
void main() => trainOutfitPart();

const _datasetRoot = r'D:\fyp project\dataset';
const _perRealClass = 400;

const _realFolders = <String, String>{
  'bag': r'train\train\accessories\bag',
  'hat': r'train\train\accessories\hat',
  'trousers': r'train\train\bottomwear\pants',
  'shorts': r'train\train\bottomwear\shorts',
  'skirt': r'train\train\bottomwear\skirt',
  'flats': r'train\train\footwear\flats',
  'heels': r'train\train\footwear\heels',
  'shoes': r'train\train\footwear\shoes',
  'sneakers': r'train\train\footwear\sneakers',
  'dress': r'train\train\one-piece\dress',
  'jacket': r'train\train\upperwear\jacket',
  'shirt': r'train\train\upperwear\shirt',
  't-shirt': r'train\train\upperwear\tshirt',
};

const _familyOf = <String, String>{
  'bag': 'accessory',
  'hat': 'accessory',
  'trousers': 'lowerwear',
  'shorts': 'lowerwear',
  'skirt': 'lowerwear',
  'flats': 'footwear',
  'heels': 'footwear',
  'shoes': 'footwear',
  'sneakers': 'footwear',
  'dress': 'dress',
  'jacket': 'upperwear',
  'shirt': 'upperwear',
  't-shirt': 'upperwear',
};

const _familyLabels = [
  'accessory',
  'footwear',
  'dress',
  'lowerwear',
  'upperwear',
];
const _footwearLabels = ['flats', 'heels', 'shoes', 'sneakers'];
const _bottomLabels = ['trousers', 'shorts', 'skirt'];
const _topLabels = ['t-shirt', 'shirt', 'jacket'];
const _accessoryLabels = ['bag', 'hat'];

const _hardClasses = {
  'dress',
  'jacket',
  'flats',
  'shorts',
  'skirt',
  'bag',
  'heels',
};

void trainOutfitPart() {
  final rng = Random(24);
  final xs = <List<double>>[];
  final leaves = <String>[];

  var realCount = 0;
  for (final entry in _realFolders.entries) {
    final dir = Directory('$_datasetRoot\\${entry.value}');
    if (!dir.existsSync()) {
      stdout.writeln('missing ${dir.path}');
      continue;
    }
    final files = dir
        .listSync()
        .whereType<File>()
        .where((f) {
          final n = f.path.toLowerCase();
          return n.endsWith('.png') ||
              n.endsWith('.jpg') ||
              n.endsWith('.jpeg') ||
              n.endsWith('.webp');
        })
        .toList()
      ..shuffle(rng);
    var added = 0;
    for (final file in files) {
      if (added >= _perRealClass) break;
      try {
        final desc = LocalImageAnalysis.describe(file.readAsBytesSync());
        if (desc == null) continue;
        xs.add(desc.features);
        leaves.add(entry.key);
        added++;
        realCount++;
      } catch (_) {}
    }
    stdout.writeln('loaded $added ${entry.key} from dataset');
  }

  stdout.writeln('training on $realCount real photos, dim=${xs.first.length}');
  final dim = xs.first.length;

  ({List<List<double>> w, List<double> b}) fit(
    List<String> labels,
    bool Function(int i) keep,
    String title, {
    int epochs = 75,
  }) {
    final subX = <List<double>>[];
    final subY = <int>[];
    for (var i = 0; i < xs.length; i++) {
      if (!keep(i)) continue;
      final y = labels.indexOf(leaves[i]);
      if (y < 0) continue;
      subX.add(xs[i]);
      subY.add(y);
    }
    stdout.writeln('$title: ${subX.length} samples, ${labels.length} classes');
    final hard = {
      for (var c = 0; c < labels.length; c++)
        if (_hardClasses.contains(labels[c])) c,
    };
    final model = _fitSoftmax(
      subX,
      subY,
      labels.length,
      dim,
      epochs: epochs,
      hard: hard,
    );
    _printAcc(title, subX, subY, labels, model.w, model.b);
    return model;
  }

  final familyYs = [
    for (var i = 0; i < leaves.length; i++)
      _familyLabels.indexOf(_familyOf[leaves[i]]!),
  ];
  stdout.writeln('family: ${xs.length} samples, ${_familyLabels.length} classes');
  final family = _fitSoftmax(
    xs,
    familyYs,
    _familyLabels.length,
    dim,
    epochs: 90,
    hard: {2, 0, 3},
  );
  _printAcc('family', xs, familyYs, _familyLabels, family.w, family.b);

  final footwear = fit(
    _footwearLabels,
    (i) => _familyOf[leaves[i]] == 'footwear',
    'footwear',
  );
  final bottom = fit(
    _bottomLabels,
    (i) => _familyOf[leaves[i]] == 'lowerwear',
    'bottom',
  );
  final top = fit(
    _topLabels,
    (i) => _familyOf[leaves[i]] == 'upperwear',
    'top',
  );
  final accessory = fit(
    _accessoryLabels,
    (i) => _familyOf[leaves[i]] == 'accessory',
    'accessory',
    epochs: 85,
  );

  final buf = StringBuffer()
    ..writeln(
      '/// Generated by `flutter pub run tool/train_outfit_part.dart`. Do not edit by hand.',
    )
    ..writeln('class OutfitPartWeights {');
  _writeHead(buf, 'family', _familyLabels, family.w, family.b);
  _writeHead(buf, 'footwear', _footwearLabels, footwear.w, footwear.b);
  _writeHead(buf, 'bottom', _bottomLabels, bottom.w, bottom.b);
  _writeHead(buf, 'top', _topLabels, top.w, top.b);
  _writeHead(buf, 'accessory', _accessoryLabels, accessory.w, accessory.b);
  buf.writeln('}');
  File('lib/services/outfit_part_weights.dart').writeAsStringSync(buf.toString());
  stdout.writeln('wrote lib/services/outfit_part_weights.dart');

  String predictLeaf(List<double> x) {
    final name = _familyLabels[_argmax(x, family.w, family.b)];
    return switch (name) {
      'accessory' => _accessoryLabels[_argmax(x, accessory.w, accessory.b)],
      'footwear' => _footwearLabels[_argmax(x, footwear.w, footwear.b)],
      'dress' => 'dress',
      'lowerwear' => _bottomLabels[_argmax(x, bottom.w, bottom.b)],
      'upperwear' => _topLabels[_argmax(x, top.w, top.b)],
      _ => 'shirt',
    };
  }

  var valHit = 0;
  var valTot = 0;
  var famHit = 0;
  var famTot = 0;
  for (final entry in _realFolders.entries) {
    final dir = Directory(
      '$_datasetRoot\\${entry.value.replaceFirst(r'train\train', r'val\val')}',
    );
    if (!dir.existsSync()) continue;
    final files = dir
        .listSync()
        .whereType<File>()
        .where((f) {
          final n = f.path.toLowerCase();
          return n.endsWith('.png') || n.endsWith('.jpg') || n.endsWith('.jpeg');
        })
        .take(50);
    var hit = 0;
    var tot = 0;
    var familyHits = 0;
    for (final file in files) {
      final desc = LocalImageAnalysis.describe(file.readAsBytesSync());
      if (desc == null) continue;
      tot++;
      valTot++;
      famTot++;
      final predFam = _familyLabels[_argmax(desc.features, family.w, family.b)];
      if (predFam == _familyOf[entry.key]) {
        familyHits++;
        famHit++;
      }
      if (predictLeaf(desc.features) == entry.key) {
        hit++;
        valHit++;
      }
    }
    if (tot > 0) {
      stdout.writeln(
        'val ${entry.key.padRight(10)} leaf ${(100 * hit / tot).toStringAsFixed(0)}%  '
        'family ${(100 * familyHits / tot).toStringAsFixed(0)}%',
      );
    }
  }
  if (valTot > 0) {
    stdout.writeln(
      'val overall leaf ${(100 * valHit / valTot).toStringAsFixed(1)}%  '
      'family ${(100 * famHit / famTot).toStringAsFixed(1)}%',
    );
  }
}

({List<List<double>> w, List<double> b}) _fitSoftmax(
  List<List<double>> xs,
  List<int> ys,
  int classes,
  int dim, {
  int epochs = 75,
  Set<int> hard = const {},
}) {
  final w = List.generate(classes, (_) => List<double>.filled(dim, 0));
  final b = List<double>.filled(classes, 0);
  final counts = List<int>.filled(classes, 0);
  for (final y in ys) {
    counts[y]++;
  }
  final n = xs.length.toDouble();
  for (var epoch = 0; epoch < epochs; epoch++) {
    final lr = 0.95 * (1 - epoch / epochs) + 0.12;
    var loss = 0.0;
    for (var i = 0; i < xs.length; i++) {
      final x = xs[i];
      final y = ys[i];
      var boost =
          counts[y] == 0 ? 1.0 : (n / (classes * counts[y])).clamp(0.75, 2.4);
      if (hard.contains(y)) boost *= 1.35;
      final logits = List<double>.generate(classes, (c) {
        var s = b[c];
        for (var k = 0; k < dim; k++) {
          s += w[c][k] * x[k];
        }
        return s;
      });
      final m = logits.reduce(max);
      var denom = 0.0;
      final p = List<double>.generate(classes, (c) {
        final e = exp(logits[c] - m);
        denom += e;
        return e;
      });
      for (var c = 0; c < classes; c++) {
        p[c] /= denom;
      }
      loss -= log(p[y].clamp(1e-9, 1.0));
      for (var c = 0; c < classes; c++) {
        final g = (p[c] - (c == y ? 1.0 : 0.0)) * boost;
        b[c] -= lr * g / n;
        for (var k = 0; k < dim; k++) {
          w[c][k] -= lr * (g * x[k] + 0.0005 * w[c][k]) / n;
        }
      }
    }
    if (epoch == 0 || epoch == epochs - 1 || epoch % 20 == 0) {
      stdout.writeln('  epoch $epoch  loss ${(loss / n).toStringAsFixed(4)}');
    }
  }
  return (w: w, b: b);
}

int _argmax(List<double> x, List<List<double>> w, List<double> b) {
  var best = 0;
  var bestS = -1e9;
  for (var c = 0; c < w.length; c++) {
    var s = b[c];
    final n = min(w[c].length, x.length);
    for (var i = 0; i < n; i++) {
      s += w[c][i] * x[i];
    }
    if (s > bestS) {
      bestS = s;
      best = c;
    }
  }
  return best;
}

void _printAcc(
  String title,
  List<List<double>> xs,
  List<int> ys,
  List<String> labels,
  List<List<double>> w,
  List<double> b,
) {
  var hit = 0;
  for (var i = 0; i < xs.length; i++) {
    if (_argmax(xs[i], w, b) == ys[i]) hit++;
  }
  stdout.writeln('$title train ${(100 * hit / xs.length).toStringAsFixed(1)}%');
  for (var c = 0; c < labels.length; c++) {
    var tot = 0;
    var ok = 0;
    for (var i = 0; i < ys.length; i++) {
      if (ys[i] != c) continue;
      tot++;
      if (_argmax(xs[i], w, b) == c) ok++;
    }
    if (tot > 0) {
      stdout.writeln(
        '  ${labels[c].padRight(10)} ${(100 * ok / tot).toStringAsFixed(0)}%',
      );
    }
  }
}

void _writeHead(
  StringBuffer buf,
  String name,
  List<String> labels,
  List<List<double>> w,
  List<double> b,
) {
  buf
    ..writeln('  static const ${name}Labels = <String>[')
    ..writeln(labels.map((l) => "    '$l',").join('\n'))
    ..writeln('  ];')
    ..writeln()
    ..writeln('  static const ${name}Weights = <List<double>>[');
  for (final row in w) {
    buf.writeln('    [${row.map((v) => v.toStringAsFixed(5)).join(', ')}],');
  }
  buf
    ..writeln('  ];')
    ..writeln()
    ..writeln('  static const ${name}Bias = <double>[')
    ..writeln('    ${b.map((v) => v.toStringAsFixed(5)).join(', ')},')
    ..writeln('  ];')
    ..writeln();
}
